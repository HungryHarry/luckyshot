const KEY = 'luckyshot:lang';
let lang = (() => {
  try { const s = localStorage.getItem(KEY); if (s && D[s]) return s; } catch {}
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
})();

export const getLang = () => lang;
export function setLang(l) {
  if (!D[l]) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch {}
  document.documentElement.lang = l;
}

const fill = (s, p) => s.replace(/\{(\w+)\}/g, (m, k) => (p[k] ?? m));

/** Text holen. Bei Plural-Schlüsseln (key_one/key_other) entscheidet p.n. */
export function t(key, p = {}) {
  const dict = D[lang];
  let v = dict[key];
  if (v === undefined && 'n' in p) v = dict[`${key}_${Number(p.n) === 1 ? 'one' : 'other'}`];
  if (v === undefined) v = D.de[key] ?? key;
  return Array.isArray(v) ? v.map(x => fill(x, p)) : fill(String(v), p);
}
